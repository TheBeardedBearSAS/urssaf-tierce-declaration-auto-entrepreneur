namespace TheBeardedBear\UrssafTierceDeclarationAutoEntrepreneur\Infrastructure\Transaction;

use Override;
use TheBeardedBear\UrssafTierceDeclarationAutoEntrepreneur\Application\Port\TransactionManager;

/**
 * Transaction port for stores without transactions: runs the operation immediately, without any rollback.
 */
final class ImmediateTransactionManager implements TransactionManager
{
    /**
     * @template T
     *
     * @param callable(): T $operation
     * @param-immediately-invoked-callable $operation
     *
     * @return T
     */
    #[Override]
    public function transactional(callable $operation): mixed
    {
        return $operation();
    }
}
